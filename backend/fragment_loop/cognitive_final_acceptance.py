def _nonempty_text(value: object) -> bool:
    return isinstance(value, str) and bool(value.strip())


def _sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _canonical_hash(value: object) -> str:
    payload = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _string_list(value: object, *, allow_empty: bool = True) -> list[str] | None:
    if not isinstance(value, list) or any(not _nonempty_text(item) for item in value):
        return None
    if not allow_empty and not value:
        return None
    return value


def check_public_url(url: object, profile: SourceProfile) -> tuple[str, ...]:
    """Fail closed on any query/fragment/userinfo, non-https, or host/path drift."""
    if not _nonempty_text(url):
        return ("url_invalid",)
    text = str(url)
    if any(character.isspace() for character in text) or "%" in text:
        return ("url_invalid",)
    try:
        split = urlsplit(text)
    except ValueError:
        return ("url_invalid",)
    errors: list[str] = []
    if split.scheme != "https":
        errors.append("url_not_https")
    if split.username is not None or split.password is not None or "@" in split.netloc:
        errors.append("url_userinfo_not_allowed")
    if split.query:
        errors.append("url_query_not_allowed")
    if split.fragment:
        errors.append("url_fragment_not_allowed")
    if split.port is not None:
        errors.append("url_port_not_allowed")
    if split.hostname != profile.allowed_host:
        errors.append("url_host_drift")
    path = split.path or ""
    if not path.startswith(profile.allowed_path_prefix):
        errors.append("url_path_drift")
    elif ".." in PurePosixPath(path).parts:
        errors.append("url_path_escape")
    return tuple(errors)


def _validate_source_card(card: PublicSourceCard) -> tuple[str, ...]:
    errors: list[str] = []
    if not _ID_PATTERN.match(card.source_id):
        errors.append("source_id_invalid")
    source_fields = (
        "title",
        "publisher",
        "published_at",
        "body",
        "source_type",
        "scope",
        "fetched_at",
    )
    for field in source_fields:
        if not _nonempty_text(getattr(card, field)):
            errors.append(f"source_{field}_invalid")
    if len(card.body) > _MAX_SOURCE_BODY_CHARS:
        errors.append("source_body_too_long")
    return tuple(errors)


def _validate_context_card(card: ContextCard) -> tuple[str, ...]:
    errors: list[str] = []
    if not _ID_PATTERN.match(card.context_id):
        errors.append("context_id_invalid")
    if not _nonempty_text(card.title) or not _nonempty_text(card.excerpt):
        errors.append("context_text_invalid")
    ref = card.ref
    if not _nonempty_text(ref) or "://" in ref or "\\" in ref or "~" in ref:
        errors.append("context_ref_invalid")
    else:
        normalized = PurePosixPath(ref)
        parts = normalized.parts
        if (
            normalized.is_absolute()
            or ".." in parts
            or any(part in ("", ".") for part in parts)
            or str(normalized) != ref
        ):
            errors.append("context_ref_invalid")
    if not _SHA256_PATTERN.match(card.content_sha256):
        errors.append("context_hash_invalid")
    elif _sha256_text(card.excerpt) != card.content_sha256:
        errors.append("context_hash_mismatch")
    return tuple(errors)


def validate_assembled_input(value: AssembledInput) -> tuple[str, ...]:
    """Pure validation of the caller-assembled input; no filesystem access."""
    errors: list[str] = []
    if not _ID_PATTERN.match(value.fragment_id):
        errors.append("fragment_id_invalid")
    if not _nonempty_text(value.fragment_text):
        errors.append("fragment_text_invalid")
    if not _SHA256_PATTERN.match(value.fragment_content_sha256):
        errors.append("fragment_hash_invalid")
    elif _sha256_text(value.fragment_text) != value.fragment_content_sha256:
        errors.append("fragment_hash_mismatch")
    errors.extend(check_public_url(value.sanitized_public_url, value.profile))
    errors.extend(_validate_source_card(value.public_source))
    cards = value.context_cards
    if len(cards) > _MAX_CONTEXT_CARDS:
        errors.append("context_cards_too_many")
    seen: set[str] = set()
    for index, card in enumerate(cards):
        card_errors = _validate_context_card(card)
        errors.extend(f"context_{index}:{error}" for error in card_errors)
        if card.context_id in seen:
            errors.append(f"context_{index}:context_id_duplicate")
        seen.add(card.context_id)
    if value.public_source.source_id in seen:
        errors.append("source_id_collides_with_context")
    if not errors and len(build_quote_catalog(value).entries) > _MAX_CATALOG_ENTRIES:
        errors.append("quote_catalog_too_large")
    return tuple(errors)


def context_card_ids(value: AssembledInput) -> frozenset[str]:
    """The only ids a model may put in ``context_refs`` — local cards only.

    The public source id is deliberately excluded: the model never binds
    the source by name; the source ref is derived locally from the quote
    layer instead.
    """
    return frozenset(card.context_id for card in value.context_cards)


# --- Deterministic quote catalog ----------------------------------------
#
# The catalog is built by a pure local function from exactly two inputs:
# the fragment text and the already-read public source body.  The fragment
# contributes one fixed anchor ``F0``; the body is split into stable,
# ordered, non-empty segments.  URLs are treated as atomic tokens so a
# sentence split never breaks a link apart; empty segments are dropped,
# duplicate segments keep only their first occurrence, and over-long
# segments are split on secondary punctuation and then hard-cut at a fixed
# width.  Local ContextCards never enter the catalog: private context is
# user cognition background, not external evidence.

_FRAGMENT_QUOTE_ID = "F0"
_SENTENCE_ENDS = frozenset("。！？!?；;\n")
_SUB_BREAKS = frozenset("，,、：:")
_URL_PATTERN = re.compile(r"https?://[A-Za-z0-9\-._~:/?#@!$&*+,;=%\[\]]+")


@dataclass(frozen=True)
class QuoteEntry:
    """One catalog entry: a stable ID bound to verbatim text and its layer.

    ``layer`` is ``"fragment"`` for the fragment anchor, or the public
    source id owning this segment.  No other layer exists — in particular
    local context card ids are never a layer.
    """

    quote_id: str
    layer: str
    text: str


@dataclass(frozen=True)
class QuoteCatalog:
    """The deterministic verbatim quote catalog for one assembled input."""

    entries: tuple[QuoteEntry, ...]
    sha256: str

    def lookup(self, quote_id: object) -> QuoteEntry | None:
        if not isinstance(quote_id, str):
            return None
        for entry in self.entries:
            if entry.quote_id == quote_id:
                return entry
        return None


def _split_long_segment(text: str) -> list[str]:
    """Split an over-long segment deterministically: secondary punctuation
    first (delimiter kept at the end of each piece), then a fixed-width
    hard cut.  Segments within the limit pass through unchanged."""
    cleaned = text.strip()
    if not cleaned:
        return []
    if len(cleaned) <= _MAX_SEGMENT_CHARS:
        return [cleaned]
    pieces: list[str] = []
    current = ""
    for character in cleaned:
        current += character
        if character in _SUB_BREAKS:
            pieces.append(current)
            current = ""
    if current:
        pieces.append(current)
    result: list[str] = []
    for piece in pieces:
        part = piece.strip()
        if not part:
            continue
        while len(part) > _MAX_SEGMENT_CHARS:
            result.append(part[:_MAX_SEGMENT_CHARS])
            part = part[_MAX_SEGMENT_CHARS:]
        result.append(part)
    return result


def _split_source_segments(body: str) -> list[str]:
    """Split the public source body into stable, ordered, non-empty,
    deduplicated verbatim segments.  URLs stay atomic."""
    tokens: list[str] = []
    position = 0
    for match in _URL_PATTERN.finditer(body):
        if match.start() > position:
            tokens.append(body[position : match.start()])
        tokens.append(match.group(0))
        position = match.end()
    if position < len(body):
        tokens.append(body[position:])
    segments: list[str] = []
    seen: set[str] = set()

    def emit(pieces: list[str]) -> None:
        for piece in pieces:
            cleaned = piece.strip()
            # Drop whitespace-empty and pure-punctuation segments: a catalog
            # entry must carry at least one letter/digit/CJK character.
            if not any(character.isalnum() for character in cleaned):
                continue
            if cleaned in seen:
                continue
            seen.add(cleaned)
            segments.append(cleaned)

    for token in tokens:
        if _URL_PATTERN.fullmatch(token):
            emit([token])
            continue
        current = ""
        for character in token:
            current += character
            if character in _SENTENCE_ENDS:
                emit(_split_long_segment(current))
                current = ""
        if current.strip():
            emit(_split_long_segment(current))
    return segments


def build_quote_catalog(value: AssembledInput) -> QuoteCatalog:
    """Build the deterministic quote catalog; same input, same catalog."""
    entries = [
        QuoteEntry(
            quote_id=_FRAGMENT_QUOTE_ID,
            layer="fragment",
            text=value.fragment_text,
        )
    ]
    source_id = value.public_source.source_id
    for index, segment in enumerate(
        _split_source_segments(value.public_source.body), start=1
    ):
        entries.append(
            QuoteEntry(
                quote_id=f"{source_id}-q{index:02d}",
                layer=source_id,
                text=segment,
            )
        )
    sha256 = _canonical_hash(
        [
            {"quote_id": entry.quote_id, "layer": entry.layer, "text": entry.text}
            for entry in entries
        ]
    )
    return QuoteCatalog(entries=tuple(entries), sha256=sha256)


def session_identity(value: AssembledInput, authorization: str) -> str:
    """Bind fragment, URL, source, context cards, catalog, plan, authorization."""
    return _canonical_hash(
        {
            "fragment_content_sha256": value.fragment_content_sha256,
            "sanitized_public_url": value.sanitized_public_url,
            "public_source_sha256": _canonical_hash(asdict(value.public_source)),
            "context_cards_sha256": _canonical_hash(
                [asdict(card) for card in value.context_cards]
            ),
            "quote_catalog_sha256": build_quote_catalog(value).sha256,
            "plan_version": PLAN_VERSION,
            "authorization_sha256": _sha256_text(authorization),
        }
    )


