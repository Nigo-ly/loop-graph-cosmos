def _operational_path(value: object, field: str) -> Path:
    if not _nonempty_text(value):
        raise FinalAcceptanceInputError(f"manifest_{field}_invalid")
    path = Path(str(value))
    if not path.is_absolute() or ".." in path.parts:
        raise FinalAcceptanceInputError(f"manifest_{field}_invalid")
    return path


def check_local_path_safety(path: Path, *, expect: str) -> tuple[str, ...]:
    """Reject any symlink or wrong-type component among existing components.

    ``expect`` is ``"file"`` or ``"dir"`` for the target itself.  A tail that
    does not exist yet is allowed, but from the nearest existing ancestor to
    the target no component may be a symlink, and every existing ancestor
    must be a real directory.
    """
    if not path.is_absolute():
        return ("path_not_absolute",)
    current = Path(path.anchor)
    parts = path.parts[1:]
    for index, part in enumerate(parts):
        current = current / part
        last = index == len(parts) - 1
        try:
            info = current.lstat()
        except OSError:
            break
        if stat.S_ISLNK(info.st_mode):
            return ("path_component_symlink",)
        if last:
            if expect == "dir" and not stat.S_ISDIR(info.st_mode):
                return ("path_target_not_directory",)
            if expect == "file" and not stat.S_ISREG(info.st_mode):
                return ("path_target_not_regular_file",)
        elif not stat.S_ISDIR(info.st_mode):
            return ("path_ancestor_not_directory",)
    return ()


def preflight_operational_paths(value: AssembledInput) -> tuple[str, ...]:
    """Symlink/type preflight for every on-disk path the run may touch.

    Covers the ledger file, the ledger lock file, the output directory, and
    through the ancestor walk the output directory's parent chain.  Runs
    before any ledger creation, credential read, or model call.
    """
    lock_path = value.ledger_path.with_name(f".{value.ledger_path.name}.lock")
    for path, expect in (
        (value.ledger_path, "file"),
        (lock_path, "file"),
        (value.output_dir, "dir"),
    ):
        errors = check_local_path_safety(path, expect=expect)
        if errors:
            return errors
    return ()


def _str_fields(raw: dict[str, object], keys: set[str], error: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for key in keys:
        value = raw[key]
        if not isinstance(value, str):
            raise FinalAcceptanceInputError(error)
        values[key] = value
    return values


def load_manifest(path: Path) -> AssembledInput:
    """Load the strict 0600 JSON manifest; any drift fails closed."""
    path_errors = check_local_path_safety(path, expect="file")
    if path_errors:
        raise FinalAcceptanceInputError(f"manifest_path_unsafe:{path_errors[0]}")
    try:
        info = path.lstat()
    except OSError as error:
        raise FinalAcceptanceInputError("manifest_unreadable") from error
    if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode):
        raise FinalAcceptanceInputError("manifest_not_regular_file")
    if stat.S_IMODE(info.st_mode) != 0o600:
        raise FinalAcceptanceInputError("manifest_permissions_invalid")
    try:
        loaded = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise FinalAcceptanceInputError("manifest_invalid") from error
    if not isinstance(loaded, dict) or set(loaded) != _MANIFEST_KEYS:
        raise FinalAcceptanceInputError("manifest_schema_invalid")
    top = _str_fields(
        loaded,
        {"fragment_id", "fragment_text", "fragment_content_sha256", "sanitized_public_url"},
        "manifest_schema_invalid",
    )
    source_raw = loaded["public_source"]
    if not isinstance(source_raw, dict) or set(source_raw) != _SOURCE_KEYS:
        raise FinalAcceptanceInputError("manifest_source_invalid")
    source = _str_fields(source_raw, _SOURCE_KEYS, "manifest_source_invalid")
    cards_raw = loaded["context_cards"]
    if not isinstance(cards_raw, list):
        raise FinalAcceptanceInputError("manifest_context_invalid")
    cards: list[ContextCard] = []
    for card_raw in cards_raw:
        if not isinstance(card_raw, dict) or set(card_raw) != _CONTEXT_KEYS:
            raise FinalAcceptanceInputError("manifest_context_invalid")
        cards.append(
            ContextCard(**_str_fields(card_raw, _CONTEXT_KEYS, "manifest_context_invalid"))
        )
    profile_raw = loaded["source_profile"]
    if not isinstance(profile_raw, dict) or set(profile_raw) != _PROFILE_KEYS:
        raise FinalAcceptanceInputError("manifest_profile_invalid")
    profile = _str_fields(profile_raw, _PROFILE_KEYS, "manifest_profile_invalid")
    assembled = AssembledInput(
        fragment_id=top["fragment_id"],
        fragment_text=top["fragment_text"],
        fragment_content_sha256=top["fragment_content_sha256"],
        sanitized_public_url=top["sanitized_public_url"],
        public_source=PublicSourceCard(**source),
        context_cards=tuple(cards),
        profile=SourceProfile(
            allowed_host=profile["allowed_host"],
            allowed_path_prefix=profile["allowed_path_prefix"],
        ),
        output_dir=_operational_path(loaded["output_dir"], "output_dir"),
        ledger_path=_operational_path(loaded["ledger_path"], "ledger_path"),
    )
    errors = validate_assembled_input(assembled)
    if errors:
        raise FinalAcceptanceInputError(f"manifest_rejected:{errors[0]}")
    return assembled


class SessionLedger:
    """Persistent reservation ledger bound to one exact session identity.

    Same discipline as the Pilot 1 ledger: reserve before send, unknown send
    counts as consumed, no retry, no recovery, no fallback; completed stages
    are reused on restart and an incomplete reservation blocks re-sending.
    Additionally the whole ledger fails closed when the session identity
    (fragment hash, sanitized URL, public source hash, context cards hash,
    quote catalog hash, plan version, authorization hash) drifts.
    """

    def __init__(
        self,
        path: Path,
        session: str,
        *,
        catalog: QuoteCatalog,
        context_ids: frozenset[str],
    ):
        self.path = path
        self._session = session
        self._catalog = catalog
        self._context_ids = context_ids
        self._lock_path = path.with_name(f".{path.name}.lock")

    @contextmanager
    def _locked(self) -> Iterator[None]:
        for candidate in (self._lock_path, self.path):
            path_errors = check_local_path_safety(candidate, expect="file")
            if path_errors:
                raise FinalAcceptanceBudgetError(
                    f"ledger_path_unsafe:{path_errors[0]}"
                )
        self.path.parent.mkdir(parents=True, exist_ok=True)
        descriptor = os.open(self._lock_path, os.O_CREAT | os.O_RDWR, 0o600)
        try:
            fcntl.flock(descriptor, fcntl.LOCK_EX)
            yield
        finally:
            fcntl.flock(descriptor, fcntl.LOCK_UN)
            os.close(descriptor)

    def _load(self) -> dict[str, object]:
        if not self.path.exists():
            return {
                "version": PLAN_VERSION,
                "session_identity": self._session,
                "reservations": [],
            }
        if self.path.is_symlink() or not self.path.is_file():
            raise FinalAcceptanceBudgetError("ledger_path_invalid")
        try:
            loaded = json.loads(self.path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
            raise FinalAcceptanceBudgetError("ledger_invalid") from error
        if (
            not isinstance(loaded, dict)
            or set(loaded) != {"version", "session_identity", "reservations"}
            or not isinstance(loaded.get("reservations"), list)
        ):
            raise FinalAcceptanceBudgetError("ledger_invalid")
        if loaded.get("version") != PLAN_VERSION:
            raise FinalAcceptanceBudgetError("ledger_plan_version_mismatch")
        if loaded.get("session_identity") != self._session:
            raise FinalAcceptanceBudgetError("ledger_identity_mismatch")
        return loaded

    def _write(self, state: dict[str, object]) -> None:
        payload = json.dumps(
            state, ensure_ascii=False, sort_keys=True, separators=(",", ":")
        )
        descriptor, temporary = tempfile.mkstemp(
            prefix=f".{self.path.name}.", dir=self.path.parent
        )
        try:
            os.fchmod(descriptor, 0o600)
            with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
                handle.write(payload)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temporary, self.path)
        except Exception:
            try:
                os.unlink(temporary)
            except FileNotFoundError:
                pass
            raise

    def reserve(
        self,
        stage: str,
        provider: str,
        input_tokens: int,
        output_tokens: int,
    ) -> str:
        expected = _STAGE_BUDGETS.get(stage)
        if expected is None:
            raise FinalAcceptanceBudgetError("stage_not_allowed")
        if expected != (provider, input_tokens, output_tokens):
            raise FinalAcceptanceBudgetError("stage_budget_mismatch")
        with self._locked():
            state = self._load()
            reservations = state["reservations"]
            assert isinstance(reservations, list)
            if any(
                isinstance(item, dict) and item.get("stage") == stage
                for item in reservations
            ):
                raise FinalAcceptanceBudgetError("stage_already_reserved")
            completed = {
                str(item.get("stage"))
                for item in reservations
                if isinstance(item, dict) and item.get("status") == "completed"
            }
            prior = _STAGE_ORDER[: _STAGE_ORDER.index(stage)]
            if any(previous not in completed for previous in prior):
                raise FinalAcceptanceBudgetError("stage_order_violation")
            provider_count = sum(
                1
                for item in reservations
                if isinstance(item, dict) and item.get("provider") == provider
            )
            if provider_count >= _PROVIDER_LIMITS[provider]:
                raise FinalAcceptanceBudgetError("provider_call_limit_reached")
            reserved_input = sum(
                int(item.get("reserved_input_tokens", 0))
                for item in reservations
                if isinstance(item, dict)
            )
            reserved_output = sum(
                int(item.get("reserved_output_tokens", 0))
                for item in reservations
                if isinstance(item, dict)
            )
            if (
                reserved_input + input_tokens > _TOTAL_INPUT_LIMIT
                or reserved_output + output_tokens > _TOTAL_OUTPUT_LIMIT
            ):
                raise FinalAcceptanceBudgetError("total_token_limit_reached")
            reservation_id = f"final-acceptance-{uuid.uuid4().hex}"
            reservations.append(
                {
                    "reservation_id": reservation_id,
                    "stage": stage,
                    "provider": provider,
                    "reserved_input_tokens": input_tokens,
                    "reserved_output_tokens": output_tokens,
                    "status": "reserved",
                }
            )
            self._write(state)
            return reservation_id

    def complete(
        self,
        reservation_id: str,
        *,
        model_claim: str,
        prompt_tokens: int,
        completion_tokens: int,
        result: dict[str, object],
    ) -> None:
        if (
            not _nonempty_text(model_claim)
            or not isinstance(prompt_tokens, int)
            or isinstance(prompt_tokens, bool)
            or prompt_tokens < 0
            or not isinstance(completion_tokens, int)
            or isinstance(completion_tokens, bool)
            or completion_tokens < 0
        ):
            raise FinalAcceptanceBudgetError("completion_evidence_invalid")
        with self._locked():
            state = self._load()
            reservations = state["reservations"]
            assert isinstance(reservations, list)
            matches = [
                item
                for item in reservations
                if isinstance(item, dict)
                and item.get("reservation_id") == reservation_id
            ]
            if len(matches) != 1:
                raise FinalAcceptanceBudgetError("reservation_not_found")
            reservation = matches[0]
            if reservation.get("status") != "reserved":
                raise FinalAcceptanceBudgetError("reservation_already_completed")
            if prompt_tokens > int(reservation["reserved_input_tokens"]) or (
                completion_tokens > int(reservation["reserved_output_tokens"])
            ):
                raise FinalAcceptanceBudgetError("observed_usage_out_of_bounds")
            provider = str(reservation["provider"])
            if model_claim != _PROVIDER_MODELS[provider]:
                raise FinalAcceptanceBudgetError("response_model_mismatch")
            errors = validate_combined_result(
                result,
                catalog=self._catalog,
                context_ids=self._context_ids,
            )
            if errors:
                raise FinalAcceptanceBudgetError(f"stage_result_invalid:{errors[0]}")
            reservation.update(
                {
                    "status": "completed",
                    "model_claim": model_claim,
                    "prompt_tokens": prompt_tokens,
                    "completion_tokens": completion_tokens,
                    "result": result,
                }
            )
            self._write(state)

    def fail(
        self,
        reservation_id: str,
        *,
        error_category: str,
        request_sent: bool | None,
    ) -> None:
        if (
            not _nonempty_text(error_category)
            or len(error_category) > 200
            or request_sent not in (True, False, None)
        ):
            raise FinalAcceptanceBudgetError("failure_evidence_invalid")
        with self._locked():
            state = self._load()
            reservations = state["reservations"]
            assert isinstance(reservations, list)
            matches = [
                item
                for item in reservations
                if isinstance(item, dict)
                and item.get("reservation_id") == reservation_id
            ]
            if len(matches) != 1 or matches[0].get("status") != "reserved":
                raise FinalAcceptanceBudgetError("reservation_not_pending")
            matches[0].update(
                {
                    "status": "failed",
                    "error_category": error_category,
                    "request_sent": request_sent,
                }
            )
            self._write(state)

    def stage_result(self, stage: str) -> dict[str, object] | None:
        with self._locked():
            state = self._load()
        reservations = state["reservations"]
        assert isinstance(reservations, list)
        matches = [
            item
            for item in reservations
            if isinstance(item, dict) and item.get("stage") == stage
        ]
        if len(matches) != 1 or matches[0].get("status") != "completed":
            return None
        result = matches[0].get("result")
        if not isinstance(result, dict):
            raise FinalAcceptanceBudgetError("ledger_invalid")
        return result

    def stage_reserved(self, stage: str) -> bool:
        with self._locked():
            state = self._load()
        reservations = state["reservations"]
        assert isinstance(reservations, list)
        return any(
            isinstance(item, dict) and item.get("stage") == stage
            for item in reservations
        )

    def view(self) -> dict[str, object]:
        with self._locked():
            state = self._load()
        reservations = state["reservations"]
        assert isinstance(reservations, list)
        return {
            "version": state["version"],
            "session_identity": state["session_identity"],
            "reservations": reservations,
            "reserved_input_tokens": sum(
                int(item.get("reserved_input_tokens", 0))
                for item in reservations
                if isinstance(item, dict)
            ),
            "reserved_output_tokens": sum(
                int(item.get("reserved_output_tokens", 0))
                for item in reservations
                if isinstance(item, dict)
            ),
            "provider_counts": {
                provider: sum(
                    1
                    for item in reservations
                    if isinstance(item, dict) and item.get("provider") == provider
                )
                for provider in _PROVIDER_LIMITS
            },
        }


def _source_json(value: AssembledInput) -> str:
    card = asdict(value.public_source)
    card["locator"] = value.sanitized_public_url
    return json.dumps(card, ensure_ascii=False, separators=(",", ":"))


def _context_json(value: AssembledInput) -> str:
    return json.dumps(
        [
            {
                "context_id": card.context_id,
                "title": card.title,
                "excerpt": card.excerpt,
                "ref": card.ref,
            }
            for card in value.context_cards
        ],
        ensure_ascii=False,
        separators=(",", ":"),
    )


