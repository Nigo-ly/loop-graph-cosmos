# v5 wire schema: the top level allows only these predefined fields.
# ``claims`` is the single required key-authenticity field; everything
# else is an optional display field.  Any other top-level key — including
# model-emitted evidence_refs/source_id bindings, free-text quote fields,
# or self-score fields — fails closed on shape.
_RESULT_REQUIRED_KEYS = {"claims"}
_RESULT_ALLOWED_KEYS = {
    "claims",
    "inventory",
    "literal_facts",
    "structural_inferences",
    "unknowns",
    "research_questions",
    "memory_view",
    "personal_view",
    "project_view",
    "frontier_view",
    "synthesis",
}
_LIST_DISPLAY_FIELDS = (
    "literal_facts",
    "structural_inferences",
    "unknowns",
    "research_questions",
)
_LOCAL_VIEW_FIELDS = ("memory_view", "personal_view", "project_view")
_VIEW_REQUIRED_KEYS = {"analysis", "uncertainty"}
_VIEW_ALLOWED_KEYS = _VIEW_REQUIRED_KEYS | {"context_refs"}
_FRONTIER_VIEW_KEYS = {"analysis", "uncertainty"}
_SYNTHESIS_ALLOWED_KEYS = {
    "judgment",
    "opportunities",
    "risks",
    "next_steps",
    "uncertainties",
}
_SYNTHESIS_LIST_FIELDS = ("opportunities", "risks", "next_steps", "uncertainties")


def _context_refs_of(item: dict[str, object]) -> list[str] | None:
    """Parse the optional ``context_refs`` field; missing means []."""
    raw = item.get("context_refs", [])
    return _string_list(raw, allow_empty=True)


def _check_context_refs(
    refs: list[str] | None, context_ids: frozenset[str]
) -> str | None:
    if refs is None:
        return "context_refs_invalid"
    for ref in refs:
        if ref not in context_ids:
            return f"unknown_context_ref:{ref}"
    return None


def _derived_source_ref(catalog: QuoteCatalog, quote_id: object) -> str | None:
    """Derive the public source ref from a quote_id's catalog layer.

    Pure local function: ``None`` for the fragment anchor (or an unknown
    id), otherwise the owning public source id.  The model never fills
    this in — v3's real block was the model omitting exactly this field.
    """
    entry = catalog.lookup(quote_id)
    if entry is None or entry.layer == "fragment":
        return None
    return entry.layer


def derived_claim_binding(
    catalog: QuoteCatalog, item: dict[str, object]
) -> dict[str, tuple[str, ...]]:
    """Locally derived evidence binding for one claim.

    Returns ``source_refs`` (0 or 1, derived from the quote layer) and
    ``context_refs`` (the validated local context ids the model declared).
    This is the only channel through which evidence refs reach the draft
    or the sidecar.
    """
    source = _derived_source_ref(catalog, item.get("quote_id"))
    context_refs = _context_refs_of(item) or []
    return {
        "source_refs": (source,) if source is not None else (),
        "context_refs": tuple(context_refs),
    }


def _forbidden_scan(value: object) -> tuple[str, ...]:
    serialized = json.dumps(value, ensure_ascii=False)
    return tuple(
        f"forbidden_claim:{phrase}"
        for phrase in _FORBIDDEN_PHRASES
        if phrase in serialized
    )


def _check_quote_id(
    quote_id: object,
    *,
    catalog: QuoteCatalog,
    kind: str,
    index: int,
) -> QuoteEntry | str:
    """Resolve a model-returned quote_id against the deterministic catalog.

    The model never emits verbatim text; it only picks catalog IDs.  Any ID
    missing from the catalog — a hallucinated ID, a layer-foreign ID such as
    a local ContextCard id, or a non-string value — fails closed with a
    fixed category.  The resolved entry carries the real verbatim text and
    its owning layer for downstream binding checks and rendering.
    """
    entry = catalog.lookup(quote_id)
    if entry is None:
        return f"{kind}_quote_id_unknown:{index}"
    return entry


_CLAIM_REQUIRED_KEYS = {"claim_id", "text", "quote_id", "verdict"}
_CLAIM_ALLOWED_KEYS = _CLAIM_REQUIRED_KEYS | {"context_refs"}


def _validate_claims(
    value: object, *, catalog: QuoteCatalog, context_ids: frozenset[str]
) -> tuple[str, ...]:
    """Strict validation of the only required key-authenticity field."""
    if not isinstance(value, list) or not value:
        return ("claims_invalid",)
    errors: list[str] = []
    seen_claims: set[str] = set()
    for index, claim in enumerate(value):
        # The model returns only quote_id plus optional context_refs;
        # evidence_refs/source_id bindings are system-derived, so any
        # model-emitted binding field fails closed on shape.
        if (
            not isinstance(claim, dict)
            or not _CLAIM_REQUIRED_KEYS <= set(claim)
            or not set(claim) <= _CLAIM_ALLOWED_KEYS
        ):
            errors.append(f"claim_invalid:{index}")
            continue
        claim_id = claim.get("claim_id")
        if not _nonempty_text(claim_id) or str(claim_id) in seen_claims:
            errors.append(f"claim_id_invalid:{index}")
        else:
            seen_claims.add(str(claim_id))
        resolved = _check_quote_id(
            claim.get("quote_id"), catalog=catalog, kind="claim", index=index
        )
        entry: QuoteEntry | None = None
        if isinstance(resolved, str):
            errors.append(resolved)
        else:
            entry = resolved
        context_refs = _context_refs_of(claim)
        ref_error = _check_context_refs(context_refs, context_ids)
        if ref_error is not None:
            errors.append(f"claim_context_refs_invalid:{index}:{ref_error}")
            context_refs = []
        if not _nonempty_text(claim.get("text")):
            errors.append(f"claim_text_invalid:{index}")
        verdict = claim.get("verdict")
        if verdict not in _VERDICTS:
            errors.append(f"claim_verdict_invalid:{index}")
        if verdict == "not_covered":
            # not_covered must anchor on the fragment itself and carry
            # no evidence: F0 only, empty context_refs.
            if entry is not None and entry.layer != "fragment":
                errors.append(f"not_covered_quote_not_fragment:{index}")
            if context_refs:
                errors.append(f"not_covered_has_context_refs:{index}")
        elif verdict in _VERDICTS:
            # The evidence relation is quote layer + context refs;
            # at least one must bind the claim.
            if entry is not None and entry.layer == "fragment" and not context_refs:
                errors.append(f"claim_unbound:{index}")
    return tuple(errors)


def validate_combined_result(
    value: object,
    *,
    catalog: QuoteCatalog,
    context_ids: frozenset[str],
) -> tuple[str, ...]:
    """Validate the single-call result without trusting its prose.

    Only ``claims`` is required.  Optional display fields are validated
    only when present: provided-but-illegal content fails closed, while a
    missing field is not an error at all — the renderer substitutes the
    explicit local placeholder instead.
    """
    if (
        not isinstance(value, dict)
        or not _RESULT_REQUIRED_KEYS <= set(value)
        or not set(value) <= _RESULT_ALLOWED_KEYS
    ):
        return ("result_shape_invalid",)
    errors: list[str] = list(
        _validate_claims(value["claims"], catalog=catalog, context_ids=context_ids)
    )
    inventory = value.get("inventory")
    if inventory is not None and not _nonempty_text(inventory):
        errors.append("inventory_invalid")
    for field in _LIST_DISPLAY_FIELDS:
        field_value = value.get(field)
        if field_value is not None and _string_list(field_value) is None:
            errors.append(f"{field}_invalid")
    for field in _LOCAL_VIEW_FIELDS:
        view = value.get(field)
        if view is None:
            continue
        if (
            not isinstance(view, dict)
            or not _VIEW_REQUIRED_KEYS <= set(view)
            or not set(view) <= _VIEW_ALLOWED_KEYS
        ):
            errors.append(f"{field}_invalid")
            continue
        if not _nonempty_text(view.get("analysis")) or not _nonempty_text(
            view.get("uncertainty")
        ):
            errors.append(f"{field}_text_invalid")
        ref_error = _check_context_refs(_context_refs_of(view), context_ids)
        if ref_error is not None:
            errors.append(f"{field}_context_refs_invalid:{ref_error}")
    frontier = value.get("frontier_view")
    if frontier is not None:
        # frontier_view is fixed to the public source; the system binds the
        # source_id, so any model-emitted ref field fails closed on shape.
        if not isinstance(frontier, dict) or set(frontier) != _FRONTIER_VIEW_KEYS:
            errors.append("frontier_view_invalid")
        elif not _nonempty_text(frontier.get("analysis")) or not _nonempty_text(
            frontier.get("uncertainty")
        ):
            errors.append("frontier_view_text_invalid")
    synthesis = value.get("synthesis")
    if synthesis is not None:
        if not isinstance(synthesis, dict) or not set(synthesis) <= (
            _SYNTHESIS_ALLOWED_KEYS
        ):
            errors.append("synthesis_invalid")
        else:
            judgment = synthesis.get("judgment")
            if judgment is not None and not _nonempty_text(judgment):
                errors.append("synthesis_judgment_invalid")
            for field in _SYNTHESIS_LIST_FIELDS:
                items = synthesis.get(field)
                if items is not None and _string_list(items) is None:
                    errors.append(f"synthesis_{field}_invalid")
    errors.extend(_forbidden_scan(value))
    return tuple(errors)


def _execute_stage(
    ledger: SessionLedger,
    *,
    stage: str,
    prompt: str,
    adapter: ModelAdapter,
) -> dict[str, object]:
    completed = ledger.stage_result(stage)
    if completed is not None:
        return completed
    if ledger.stage_reserved(stage):
        raise FinalAcceptanceExecutionError(f"{stage}_incomplete_blocks_retry")
    provider, input_limit, output_limit = _STAGE_BUDGETS[stage]
    reservation_id = ledger.reserve(stage, provider, input_limit, output_limit)
    try:
        reply = adapter(prompt, output_limit)
    except ModelCallError as error:
        ledger.fail(
            reservation_id,
            error_category=error.category,
            request_sent=error.request_sent,
        )
        raise FinalAcceptanceExecutionError(f"{stage}_call_failed") from None
    except PilotExecutionError as error:
        ledger.fail(
            reservation_id,
            error_category=str(error),
            request_sent=None,
        )
        raise FinalAcceptanceExecutionError(f"{stage}_call_failed") from None
    except Exception:
        ledger.fail(
            reservation_id,
            error_category="unexpected_adapter_failure",
            request_sent=None,
        )
        raise FinalAcceptanceExecutionError(f"{stage}_call_failed") from None
    try:
        ledger.complete(
            reservation_id,
            model_claim=reply.model_claim,
            prompt_tokens=reply.prompt_tokens,
            completion_tokens=reply.completion_tokens,
            result=reply.result,
        )
    except FinalAcceptanceBudgetError as error:
        ledger.fail(
            reservation_id,
            error_category=str(error),
            request_sent=True,
        )
        raise FinalAcceptanceExecutionError(f"{stage}_result_rejected") from None
    result: dict[str, object] = reply.result
    return result


def run_final_acceptance(
    value: AssembledInput,
    *,
    authorization: str,
    adapter: ModelAdapter,
) -> dict[str, object]:
    """Run the frozen one-call plan; wrong authorization is zero-effect."""
    if authorization != AUTHORIZATION:
        raise FinalAcceptanceExecutionError("authorization_required")
    errors = validate_assembled_input(value)
    if errors:
        raise FinalAcceptanceInputError(f"assembled_input_invalid:{errors[0]}")
    path_errors = preflight_operational_paths(value)
    if path_errors:
        raise FinalAcceptanceExecutionError(f"path_unsafe:{path_errors[0]}")
    catalog = build_quote_catalog(value)
    session = session_identity(value, authorization)
    ledger = SessionLedger(
        value.ledger_path,
        session,
        catalog=catalog,
        context_ids=context_card_ids(value),
    )
    result = _execute_stage(
        ledger,
        stage="combined",
        prompt=_combined_prompt(value, catalog),
        adapter=adapter,
    )
    return {
        "session_identity": session,
        "fragment_id": value.fragment_id,
        "quote_catalog_sha256": catalog.sha256,
        "result": result,
        "markdown": render_draft_markdown(value, session, catalog, result),
        "ledger": ledger.view(),
    }


def _render_frontmatter(fields: tuple[tuple[str, object], ...]) -> str:
    header = "\n".join(
        f"{key}: {json.dumps(field, ensure_ascii=False, separators=(',', ':'))}"
        for key, field in fields
    )
    return f"---\n{header}\n---\n"


def _quote_line(catalog: QuoteCatalog, quote_id: object) -> str:
    """Inject the real verbatim text for a model-chosen quote_id."""
    entry = catalog.lookup(quote_id)
    if entry is None:  # unreachable: validators ran first; fail closed anyway
        raise FinalAcceptanceExecutionError("quote_catalog_drift")
    return f"{entry.quote_id}（{entry.layer}）：{entry.text}"


def _binding_text(binding: dict[str, tuple[str, ...]]) -> str:
    """Render one locally derived binding; never model free text."""
    source = "、".join(binding["source_refs"]) or "无"
    contexts = "、".join(binding["context_refs"]) or "无"
    return f"公开来源 {source}；本地上下文 {contexts}"


def _display_list(result: dict[str, object], field: str) -> list[str] | None:
    """The model-provided display list, or ``None`` when missing or empty.

    ``None`` means the renderer must emit the explicit local placeholder;
    validators already rejected any provided-but-illegal shape.
    """
    raw = result.get(field)
    if not isinstance(raw, list) or not raw:
        return None
    return [str(item) for item in raw]


def render_draft_markdown(
    value: AssembledInput,
    session: str,
    catalog: QuoteCatalog,
    result: dict[str, object],
) -> str:
    """Render the validated single-call result into the draft-only note body.

    Fully deterministic and local: every verbatim quote in the output is
    injected from the local quote catalog, every evidence binding is
    derived by local pure functions from quote layers and declared
    context_refs — never from model-emitted refs or free-text citations —
    and every section the model did not generate is shown as the explicit
    local placeholder, never as fabricated or verified content.
    """
    context_ids = context_card_ids(value)
    if validate_combined_result(result, catalog=catalog, context_ids=context_ids):
        raise FinalAcceptanceExecutionError("result_invalid")
    placeholder = MISSING_SECTION_PLACEHOLDER
    title = f"碎片认知结果草稿：{value.fragment_text.strip()[:30]}"
    frontmatter = _render_frontmatter(
        (
            ("type", "碎片认知结果"),
            ("title", title),
            ("lifecycle_status", "draft"),
            ("evidence_level", "unverified"),
            ("user_confirmed", False),
            ("promoted_to_asset", False),
            ("paper_independently_verified", False),
            ("single_model_single_call", True),
            ("fragment_id", value.fragment_id),
            ("session_identity", session),
            ("quote_catalog_sha256", catalog.sha256),
            ("plan_version", PLAN_VERSION),
        )
    )
    source = value.public_source
    lines = [
        f"# {title}",
        "",
        "## 状态与边界",
        "",
        "- 本笔记是 `draft + unverified` 草稿：用户尚未确认，未提升为资产。",
        "- 全部模型内容来自同一模型 DeepSeek V4 Pro 的单次调用（盘点与综合同源）："
        "不构成独立模型复核，相关性风险未消除，使用前必须人工确认。",
        "- 公开页面是媒体二手来源：其中转述的论文数字未独立核验原论文。",
        "- 本地上下文是用户既有认知材料，不作为外部事实来源。",
        "- 全部逐字引用来自本地确定性引用目录，模型只选择了 quote_id。",
        "- 全部证据绑定（公开来源 source_id 与本地 context_id）由本地纯函数"
        "按 quote_id 层与申报的 context_refs 推导，模型不返回任何绑定字段。",
        f"- 标注「{placeholder}」的区块是本地占位：模型本次未产出该内容，"
        "系统不补写任何事实，也不代表该部分已验证。",
        "",
        "## 原始碎片",
        "",
        f"> {value.fragment_text}",
        "",
        "## 公开来源（媒体二手来源）",
        "",
        f"- **{source.source_id} · {source.title}**：{source.publisher}，"
        f"{source.published_at}，{value.sanitized_public_url}",
        f"  - 范围：{source.scope}",
        "",
        "## 本地上下文（用户既有认知材料）",
        "",
    ]
    if value.context_cards:
        for card in value.context_cards:
            lines.append(f"- **{card.context_id} · {card.title}**（引用：{card.ref}）")
    else:
        lines.append("- 本轮未选择本地上下文。")
    lines.extend(["", "## 逐字引用目录（本地确定性构造）", ""])
    for entry in catalog.entries:
        lines.append(f"- **{entry.quote_id}**（{entry.layer}）：{entry.text}")
    lines.extend(["", "## 信息盘点（单次 DeepSeek 调用）", ""])
    inventory = result.get("inventory")
    lines.append(str(inventory) if _nonempty_text(inventory) else placeholder)
    for heading, field in (
        ("字面事实", "literal_facts"),
        ("结构推断", "structural_inferences"),
        ("未知", "unknowns"),
        ("研究问题", "research_questions"),
    ):
        lines.extend(["", f"### {heading}", ""])
        items = _display_list(result, field)
        if items is None:
            lines.append(f"- {placeholder}")
        else:
            lines.extend(f"- {item}" for item in items)
    lines.extend(["", "## 主张与证据绑定（本地推导）", ""])
    claims = result["claims"]
    assert isinstance(claims, list)
    claim_bindings: dict[str, dict[str, tuple[str, ...]]] = {}
    for claim in claims:
        assert isinstance(claim, dict)
        binding = derived_claim_binding(catalog, claim)
        claim_bindings[str(claim["claim_id"])] = binding
        lines.append(
            f"- **{claim['claim_id']} · {claim['verdict']}**：{claim['text']}"
            f"（证据绑定（本地推导）：{_binding_text(binding)}；"
            f"原文 {_quote_line(catalog, claim['quote_id'])}）"
        )
    for heading, key in (
        ("现有记忆视角（仅基于本地上下文，属用户既有认知）", "memory_view"),
        ("个人认知与偏好视角（仅基于本地上下文，属用户既有认知）", "personal_view"),
        ("知识库与项目进展视角（仅基于本地材料）", "project_view"),
    ):
        lines.extend(["", f"## {heading}", ""])
        # No selected local card means there is no factual basis for any
        # memory, preference, or project claim.  Model prose is ignored even
        # when it was returned: the human-facing draft must not turn a
        # single-model guess into a user profile.
        if not value.context_cards:
            lines.append("本轮未选择本地上下文，无法形成该视角判断。")
            continue
        view = result.get(key)
        if not isinstance(view, dict):
            lines.append(placeholder)
            continue
        used = "、".join(_context_refs_of(view) or []) or "无"
        lines.append(str(view["analysis"]))
        lines.append(f"\n使用本地上下文（模型申报，仅限 context_id）：{used}")
        lines.append(f"\n不确定性：{view['uncertainty']}")
    lines.extend(["", "## 前沿行业／技术／科学视角（仅基于公开来源）", ""])
    frontier = result.get("frontier_view")
    if not isinstance(frontier, dict):
        lines.append(placeholder)
    else:
        lines.append(str(frontier["analysis"]))
        lines.append(f"\n证据绑定（本地推导，仅限公开来源）：{source.source_id}")
        lines.append(f"\n不确定性：{frontier['uncertainty']}")
    all_sources = sorted(
        {ref for binding in claim_bindings.values() for ref in binding["source_refs"]}
        | {source.source_id}
    )
    all_contexts = sorted(
        {ref for binding in claim_bindings.values() for ref in binding["context_refs"]}
    )
    union_text = _binding_text(
        {"source_refs": tuple(all_sources), "context_refs": tuple(all_contexts)}
    )
    lines.extend(["", "## 综合判断", ""])
    synthesis = result.get("synthesis")
    if not isinstance(synthesis, dict):
        lines.append(placeholder)
    else:
        judgment = synthesis.get("judgment")
        lines.append(str(judgment) if _nonempty_text(judgment) else placeholder)
        for label, key in (
            ("机会", "opportunities"),
            ("风险", "risks"),
            ("下一步", "next_steps"),
            ("不确定性", "uncertainties"),
        ):
            lines.extend(["", f"### {label}", ""])
            items = _display_list(synthesis, key)
            if items is None:
                lines.append(f"- {placeholder}")
            else:
                lines.extend(f"- {item}" for item in items)
    lines.extend(["", f"证据绑定汇总（本地推导）：{union_text}"])
    return frontmatter + "\n" + "\n".join(lines).rstrip() + "\n"


def publish_draft(value: AssembledInput, artifact: dict[str, object]) -> dict[str, object]:
    """Atomically, idempotently publish exactly one draft plus one sidecar."""
    session = artifact.get("session_identity")
    markdown = artifact.get("markdown")
    result = artifact.get("result")
    catalog = build_quote_catalog(value)
    if (
        not _nonempty_text(session)
        or session != session_identity(value, AUTHORIZATION)
        or artifact.get("quote_catalog_sha256") != catalog.sha256
        or not _nonempty_text(markdown)
        or not isinstance(result, dict)
    ):
        raise FinalAcceptanceExecutionError("artifact_invalid")
    refs = context_card_ids(value)
    if validate_combined_result(result, catalog=catalog, context_ids=refs):
        raise FinalAcceptanceExecutionError("artifact_invalid")
    base = f"fragment-cognition-{value.fragment_id}-{str(session)[:16]}"
    markdown_bytes = str(markdown).encode("utf-8")
    ledger = artifact.get("ledger")
    reservations = ledger.get("reservations") if isinstance(ledger, dict) else None
    call_evidence: list[dict[str, object]] = []
    if isinstance(reservations, list):
        for item in reservations:
            if not isinstance(item, dict):
                continue
            call_evidence.append(
                {
                    key: item[key]
                    for key in (
                        "stage",
                        "provider",
                        "status",
                        "model_claim",
                        "prompt_tokens",
                        "completion_tokens",
                    )
                    if key in item
                }
            )
    # Every evidence ref in the sidecar is generated by local pure
    # functions (quote layer derivation + declared context_refs), never by
    # model-emitted binding fields.
    claim_bindings: dict[str, object] = {}
    claims = result.get("claims")
    assert isinstance(claims, list)
    for claim in claims:
        assert isinstance(claim, dict)
        binding = derived_claim_binding(catalog, claim)
        claim_bindings[str(claim["claim_id"])] = {
            "quote_id": str(claim["quote_id"]),
            "source_refs": list(binding["source_refs"]),
            "context_refs": list(binding["context_refs"]),
        }
    sidecar = {
        "plan_version": PLAN_VERSION,
        "session_identity": session,
        "quote_catalog_sha256": catalog.sha256,
        "fragment_id": value.fragment_id,
        "lifecycle_status": "draft",
        "evidence_level": "unverified",
        "user_confirmed": False,
        "promoted_to_asset": False,
        "paper_independently_verified": False,
        "single_model_single_call": True,
        "draft_sha256": hashlib.sha256(markdown_bytes).hexdigest(),
        "evidence_bindings": {
            "derived_locally": True,
            "claims": claim_bindings,
            "frontier_view": {"source_refs": [value.public_source.source_id]},
        },
        "model_calls": call_evidence,
    }
    payloads = {
        f"{base}.md": markdown_bytes,
        f"{base}.json": (
            json.dumps(sidecar, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
            + "\n"
        ).encode("utf-8"),
    }
    output_dir = value.output_dir
    path_errors = check_local_path_safety(output_dir, expect="dir")
    if path_errors:
        raise FinalAcceptanceExecutionError(f"path_unsafe:{path_errors[0]}")
    if output_dir.exists():
        names = {path.name for path in output_dir.iterdir()}
        if names != set(payloads):
            raise FinalAcceptanceExecutionError("publish_conflict")
        for name, payload in payloads.items():
            path = output_dir / name
            if path.is_symlink() or not path.is_file() or path.read_bytes() != payload:
                raise FinalAcceptanceExecutionError("publish_conflict")
        status = "already_published"
    else:
        parent = output_dir.parent
        prefix = f".{output_dir.name}.staging-"
        if parent.exists():
            # Any staging residue from a previous run — directory, plain file,
            # or symlink — fails closed with zero byte changes; only staging
            # created by this very publish attempt may be cleaned up below.
            for leftover in parent.iterdir():
                if leftover.name.startswith(prefix):
                    raise FinalAcceptanceExecutionError("publish_staging_residue")
        parent.mkdir(parents=True, exist_ok=True)
        staging = Path(tempfile.mkdtemp(prefix=prefix, dir=parent))
        try:
            for name, payload in payloads.items():
                path = staging / name
                path.write_bytes(payload)
                path.chmod(0o600)
            os.replace(staging, output_dir)
        except Exception:
            for path in staging.iterdir():
                path.unlink()
            staging.rmdir()
            raise
        status = "published"
    return {
        "status": status,
        "files": sorted(payloads),
        "draft_sha256": sidecar["draft_sha256"],
    }


def selfcheck() -> dict[str, object]:
    """Pure offline invariants of the frozen plan; no filesystem or network."""
    checks: dict[str, str] = {}
    total_input = sum(budget[1] for budget in _STAGE_BUDGETS.values())
    total_output = sum(budget[2] for budget in _STAGE_BUDGETS.values())
    checks["total_input_limit"] = (
        "ok" if total_input == _TOTAL_INPUT_LIMIT == 10_000 else "failed"
    )
    checks["total_output_limit"] = (
        "ok" if total_output == _TOTAL_OUTPUT_LIMIT == 7_000 else "failed"
    )
    glm_calls = sum(1 for budget in _STAGE_BUDGETS.values() if budget[0] == "glm47")
    deepseek_calls = sum(
        1 for budget in _STAGE_BUDGETS.values() if budget[0] == "deepseek_v4_pro"
    )
    checks["plan_provider_calls"] = (
        "ok"
        if glm_calls == 0
        and deepseek_calls == 1
        and deepseek_calls == _PROVIDER_LIMITS["deepseek_v4_pro"]
        and len(_PROVIDER_LIMITS) == 1
        else "failed"
    )
    profile = SourceProfile(allowed_host="example.com", allowed_path_prefix="/research/")
    checks["url_accepts_clean_https"] = (
        "ok" if not check_public_url("https://example.com/research/a", profile) else "failed"
    )
    bad_urls = (
        "https://example.com/research/a?uid=1",
        "https://example.com/research/a#frag",
        "https://user@example.com/research/a",
        "http://example.com/research/a",
        "https://other.example.net/research/a",
        "https://example.com/other/a",
    )
    checks["url_rejects_drift"] = (
        "ok" if all(check_public_url(url, profile) for url in bad_urls) else "failed"
    )
    status = "ok" if all(result == "ok" for result in checks.values()) else "failed"
    return {"status": status, "checks": checks, "plan_version": PLAN_VERSION}
